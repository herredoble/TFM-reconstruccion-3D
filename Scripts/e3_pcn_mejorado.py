"""### Visualizar el resultado (mejor checkpoint según val loss)"""

def visualizar_reconstruccion(roto, prediccion, completo, titulo=""):
    fig = plt.figure(figsize=(15, 5))

    datos = [
        (roto, "Entrada (rota)"),
        (prediccion, "Predicción del modelo"),
        (completo, "Ground truth (completo)")
    ]

    for i, (puntos, nombre) in enumerate(datos):
        ax = fig.add_subplot(1, 3, i + 1, projection='3d')
        puntos = puntos.cpu().numpy()
        ax.scatter(puntos[:, 0], puntos[:, 1], puntos[:, 2], s=2, alpha=0.6)
        ax.set_title(nombre)
        ax.set_xlim(-1, 1)
        ax.set_ylim(-1, 1)
        ax.set_zlim(-1, 1)

    plt.suptitle(titulo)
    plt.tight_layout()
    plt.show()

model.eval()

# Visualizamos varios ejemplos de validación, no solo el primero, para hacernos
# una idea más fiable de si el modelo generaliza o solo acierta en un caso suelto.
n_ejemplos = min(3, len(val_set))
for i in range(n_ejemplos):
    roto, completo = val_set[i]
    roto_batch = roto.unsqueeze(0).cuda()  # añadir dimensión de batch: (1, 2048, 3)

    with torch.no_grad():
        coarse_pred, dense_pred = model(roto_batch)

    prediccion = dense_pred[0]
    prediccion_coarse = coarse_pred[0]

    visualizar_reconstruccion(roto, prediccion, completo, titulo=f"Validación #{i} — FINE")
    visualizar_reconstruccion(roto, prediccion_coarse, completo, titulo=f"Validación #{i} — COARSE")

