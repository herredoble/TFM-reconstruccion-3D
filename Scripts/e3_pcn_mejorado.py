"""### Imports generales"""

import os, glob, random
import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader, Subset

# Semilla fija
SEED = 42
random.seed(SEED)
np.random.seed(SEED)
torch.manual_seed(SEED)

"""### Datos (carga y formato)
- Hay 61 pares (completo/roto).
- Cada par son dos archivos .npy
- Shape: (2048, 3) — 2.048 puntos, coordenadas XYZ
- Dtype: float32
- Normalización: centrado en el origen, escalado a esfera unidad
"""

ruta_datos ="/content/drive/MyDrive/Datos_E2/Fantastik_Break_Preprocesado"
print(os.listdir(ruta_datos)[:10])

class FantasticBreaksDataset(Dataset):
    """
    augmentar=True activa augmentación (rotación aleatoria en Z + jitter gaussiano
    ligero en la nube rota). Con solo ~60 pares reales, la augmentación es la forma
    más barata de darle al modelo más variedad efectiva sin datos nuevos.
    La rotación se aplica IGUAL a roto y completo para no romper la correspondencia
    punto-a-punto entre ambos. El jitter solo se aplica a la entrada (roto), nunca
    al ground truth.
    """
    def __init__(self, carpeta, augmentar=False, jitter_std=0.01):
        self.pares = []
        self.augmentar = augmentar
        self.jitter_std = jitter_std
        rotos = sorted(glob.glob(os.path.join(carpeta, "*_roto.npy")))
        for r in rotos:
            c = r.replace("_roto.npy", "_completo.npy")
            if os.path.exists(c):
                self.pares.append((r, c))

    def __len__(self):
        return len(self.pares)

    def _augmentar(self, roto, completo):
        # Rotación aleatoria alrededor del eje Z (misma rotación para los dos)
        theta = np.random.uniform(0, 2 * np.pi)
        c, s = np.cos(theta), np.sin(theta)
        R = np.array([[c, -s, 0],
                      [s,  c, 0],
                      [0,  0, 1]], dtype=np.float32)
        roto = roto @ R.T
        completo = completo @ R.T

        # Jitter gaussiano leve solo en la entrada rota (simula ruido de escaneo)
        roto = roto + np.random.normal(0, self.jitter_std, roto.shape).astype(np.float32)

        return roto, completo

    def __getitem__(self, idx):
        r_path, c_path = self.pares[idx]
        roto = np.load(r_path).astype(np.float32)
        completo = np.load(c_path).astype(np.float32)

        if self.augmentar:
            roto, completo = self._augmentar(roto, completo)

        return torch.from_numpy(roto), torch.from_numpy(completo)

# Dataset base (sin augmentar) para poder ver cuántos pares hay y para validación
dataset_base = FantasticBreaksDataset(ruta_datos, augmentar=False)
print(f"Pares encontrados: {len(dataset_base)}")

"""### División de los datos
Train / validation / test

Nota: se hace un split por índices (no random_split) para poder tener dos
instancias del dataset -- una CON augmentación (para train) y otra SIN
augmentación (para validación) -- pero compartiendo exactamente los mismos
índices de división.
"""

n_val = 8
n_train = len(dataset_base) - n_val  # 53

indices = list(range(len(dataset_base)))
random.shuffle(indices)
